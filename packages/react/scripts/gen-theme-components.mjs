// Writes src/theme/components.ts: the plain `ThemeComponents` interface, one optional key per
// component that has a `<Name>.types.ts` exporting `<Name>ThemeConfig`. The component folders are
// the one source; nothing in a component declares into another module.
//
//   node scripts/gen-theme-components.mjs [--check]
//
// `--check` writes nothing and fails when the file is not what the folders say (the commit hook
// and CI run it).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = join(root, 'src')
const target = join(src, 'theme', 'components.ts')

const typesFiles = (folder) =>
  readdirSync(folder, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory()
      ? typesFiles(join(folder, entry.name))
      : entry.name.endsWith('.types.ts')
        ? [join(folder, entry.name)]
        : []
  )

/** The text of src/theme/components.ts, from the component folders. */
export const generate = () => {
  const components = typesFiles(src)
    .map((file) => ({
      file,
      key: /export type (\w+)ThemeConfig\b/.exec(readFileSync(file, 'utf8'))?.[1],
    }))
    .filter(({ key }) => key)
    .sort((a, b) => (a.key < b.key ? -1 : 1))
  const imports = components.map(({ file, key }) => {
    const path = relative(dirname(target), file).split(sep).join('/').replace(/\.ts$/, '')
    return `import type { ${key}ThemeConfig } from '${path}'`
  })
  const keys = components.map(({ key }) => `  ${key}?: ${key}ThemeConfig`)
  return `// Generated by \`pnpm gen:theme-components\` from the \`*.types.ts\` files of the components. Do not edit.
${imports.join('\n')}

/**
 * Per-component theme customization, keyed by component name: each key takes the component's
 * \`<Name>ThemeConfig\` - its owner state, its slots, its default props and variants. An app checks
 * its looks against it with \`satisfies ThemeComponents\`.
 */
export interface ThemeComponents {
${keys.join('\n')}
}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = generate()
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== next) {
      console.error('src/theme/components.ts is out of date: run `pnpm gen:theme-components`.')
      process.exit(1)
    }
  } else {
    writeFileSync(target, next)
  }
}
