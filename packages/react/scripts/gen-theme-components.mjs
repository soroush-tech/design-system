// Writes what the component folders say about `theme.components`, from their `<Name>.types.ts`
// files (each exports `<Name>ThemeConfig`, built from `ComponentConfig<OwnerState, Slot>`):
//
// - src/theme/components.ts: the plain `ThemeComponents` interface, one optional key per component;
// - ../core/src/catalog/themeComponents.ts: each component's slot names and owner-state fields, the
//   data the catalog carries and the development validator reads.
//
// The component folders are the one source; nothing in a component declares into another module.
//
//   node scripts/gen-theme-components.mjs [--check]
//
// `--check` writes nothing and fails when a file is not what the folders say (the commit hook and
// CI run it).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = join(root, 'src')
const target = join(src, 'theme', 'components.ts')
const dataTarget = join(root, '..', 'core', 'src', 'catalog', 'themeComponents.ts')
const slotsTarget = join(root, 'type-tests', 'slots.ts')

const typesFiles = (folder) =>
  readdirSync(folder, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory()
      ? typesFiles(join(folder, entry.name))
      : entry.name.endsWith('.types.ts')
        ? [join(folder, entry.name)]
        : []
  )

/** The text between the braces that follow `start`, nested braces included. */
const block = (text, start) => {
  const open = text.indexOf('{', start)
  let depth = 0
  for (let at = open; at < text.length; at++) {
    if (text[at] === '{') depth++
    if (text[at] === '}' && --depth === 0) return text.slice(open + 1, at)
  }
  return ''
}

/** The names of the fields at the top level of an interface body. */
const fieldsOf = (body) => {
  const names = []
  let depth = 0
  for (const line of body.split('\n')) {
    const field = depth === 0 && /^\s*(?:readonly\s+)?(\w+)\??:/.exec(line)
    if (field) names.push(field[1])
    for (const char of line) depth += char === '{' ? 1 : char === '}' ? -1 : 0
  }
  return names
}

/** The string literals of the union `type <name> = 'a' | 'b'`. */
const literalsOf = (text, name) => {
  const start = text.search(new RegExp(String.raw`type ${name}\s*=`))
  const end = text.indexOf('\n\n', start)
  return [...text.slice(start, end < 0 ? undefined : end).matchAll(/'([^']+)'/g)].map((m) => m[1])
}

const components = typesFiles(src)
  .map((file) => {
    const text = readFileSync(file, 'utf8')
    const config =
      /export type (\w+)ThemeConfig\s*=\s*ComponentConfig<\s*(\w+)(?:,\s*(\w+))?\s*,?\s*>/.exec(
        text
      )
    if (!config) return null
    const [, key, owner, slot] = config
    const fields = fieldsOf(
      block(text, text.search(new RegExp(String.raw`(?:interface|type) ${owner}\b`)))
    )
    return {
      file,
      key,
      // An owner state that lists no fields (`Record<string, unknown>`, or one derived from another) is open.
      ownerState: fields.length ? fields : undefined,
      slots: slot ? literalsOf(text, slot) : ['root'],
    }
  })
  .filter(Boolean)
  .sort((a, b) => (a.key < b.key ? -1 : 1))

const list = (names) => `[${names.map((name) => `'${name}'`).join(', ')}]`

/** The text of src/theme/components.ts, from the component folders. */
export const generate = () => {
  const imports = components.map(({ file, key }) => {
    const path = relative(dirname(target), file).split(sep).join('/').replace(/\.ts$/, '')
    return `import type { ${key}ThemeConfig } from '${path}'`
  })
  const keys = components.map(({ key }) => `  ${key}?: ${key}ThemeConfig`)
  return `// Generated by \`pnpm gen:theme-components\` from the \`*.types.ts\` files of the components. Do not edit.
${imports.join('\n')}

/**
 * Per-component theme customization, keyed by component name: each key takes the component's
 * \`<Name>ThemeConfig\` - its owner state, its slots, its default props and variants. An app checks
 * its looks against it with \`satisfies ThemeComponents\`.
 */
export interface ThemeComponents {
${keys.join('\n')}
}
`
}

/** The text of core's src/catalog/themeComponents.ts: the slots and owner-state fields of each component. */
export const generateData =
  () => `// Generated by \`pnpm gen:theme-components\` from the \`*.types.ts\` files of the React components. Do not edit.

/**
 * What a component's \`theme.components\` entry may name: its slots, and the fields of its owner state
 * (its props, as resolved) - left out when the component's owner state is open.
 */
export const themeComponents: Record<string, { slots: string[]; ownerState?: string[] }> = {
${components
  .map(
    ({ key, slots, ownerState }) =>
      `  ${key}: { slots: ${list(slots)}${ownerState ? `, ownerState: ${list(ownerState)}` : ''} },`
  )
  .join('\n')}
}
`

/** The text of type-tests/slots.ts: each component's `slotProps` keys held equal to the slots the catalog lists. */
export const generateSlotsTest = () => {
  const byEntry = new Map()
  for (const { file, key } of components) {
    const entry = relative(src, file).split(sep)[0]
    byEntry.set(entry, [...(byEntry.get(entry) ?? []), `${key}Props`])
  }
  const imports = [...byEntry]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(
      ([entry, names]) =>
        `import type { ${names.sort().join(', ')} } from '@gild-ui/react/${entry}'`
    )
  const rows = components.map(
    ({ key, slots }) =>
      `  Same<SlotKeys<${key}Props>, ${slots.map((slot) => `'${slot}'`).join(' | ')}>,`
  )
  return `// Generated by \`pnpm gen:theme-components\` from the \`*.types.ts\` files of the components. Do not edit.
// Each component's \`slotProps\` is keyed by exactly the slots its \`<Name>Slot\` type declares, the list the
// catalog gives it: a prop that names another set, or none, fails here. Runs via \`pnpm test:types\`.
${imports.join('\n')}

type SlotKeys<Props> = Props extends { slotProps?: infer Slots } ? keyof NonNullable<Slots> : never
type Same<A, B> = [A] extends [B] ? ([B] extends [A] ? true : false) : false

export const slots: [
${rows.join('\n')}
] = [${components.map(() => 'true').join(', ')}]
`
}

const files = [
  [target, generate],
  [dataTarget, generateData],
  [slotsTarget, generateSlotsTest],
]

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check')
  for (const [path, make] of files) {
    if (!check) writeFileSync(path, make())
    else if (readFileSync(path, 'utf8') !== make()) {
      console.error(
        `${relative(process.cwd(), path)} is out of date: run \`pnpm gen:theme-components\`.`
      )
      process.exit(1)
    }
  }
}
